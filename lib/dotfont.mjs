// glyph advance in dot cells (5 glyph + 1 gap)
export function measure(str, pitch) {
  return str.length ? str.length * 6 * pitch - pitch : 0;
}

/**
 * Draw dot-matrix text.
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} str
 * @param {number} x  left edge
 * @param {number} y  top edge
 * @param {object} o  {size, color, glow, pitch, dot, alpha}
 *   size  = height of the 7-row cap in px
 *   pitch = distance between dot centres (default size/7 * 1.35)
 *   dot   = dot side as a fraction of pitch (default 0.72)
 */
export function dotText(ctx, str, x, y, o = {}) {
  const size = o.size ?? 42;
  const pitch = o.pitch ?? size / 7;
  const dot = (o.dot ?? 0.74) * pitch;
  const color = o.color ?? "#9FDD4E";
  const text = String(str).toUpperCase();
  const r = Math.max(0.5, Math.min(2.2, pitch * 0.12));
  ctx.save();
  ctx.globalAlpha = o.alpha ?? 1;
  ctx.fillStyle = color;
  if (o.glow) {
    ctx.shadowColor = color;
    ctx.shadowBlur = o.glow;
  }
  let cx = x;
  for (const ch of text) {
    const g = G[ch] ?? G["?"];
    for (let row = 0; row < 7; row++) {
      const line = g[row];
      for (let col = 0; col < 5; col++) {
        if (line[col] !== "#") continue;
        const px = cx + col * pitch;
        const py = y + row * pitch;
        if (r >= dot / 2) ctx.fillRect(px, py, dot, dot);
        else {
          ctx.beginPath();
          ctx.roundRect(px + (pitch - dot) / 2, py + (pitch - dot) / 2, dot, dot, r);
          ctx.fill();
        }
      }
    }
    cx += pitch * 6;
  }
  ctx.restore();
  return cx - x - pitch;
}

// Reveal only the first `n` dot columns of a string (type-on effect).
export function dotTextTypeOn(ctx, str, x, y, n, o = {}) {
  const text = String(str).toUpperCase();
  const size = o.size ?? 42;
  const pitch = o.pitch ?? size / 7;
  const dot = (o.dot ?? 0.74) * pitch;
  const color = o.color ?? "#9FDD4E";
  const r = Math.max(0.5, Math.min(2.2, pitch * 0.12));
  ctx.save();
  ctx.fillStyle = color;
  let col = 0;
  for (const ch of text) {
    const g = G[ch] ?? G["?"];
    for (let row = 0; row < 7; row++) {
      for (let c = 0; c < 5; c++) {
        if (g[row][c] !== "#") continue;
        if (col + c >= n) continue;
        const px = x + (col + c) * pitch;
        const py = y + row * pitch;
        if (r >= dot / 2) ctx.fillRect(px, py, dot, dot);
        else {
          ctx.beginPath();
          ctx.roundRect(px + (pitch - dot) / 2, py + (pitch - dot) / 2, dot, dot, r);
          ctx.fill();
        }
      }
    }
    col += 6;
  }
  ctx.restore();
  return col * pitch;
}
